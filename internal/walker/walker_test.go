// TestWalk_CachedirTagSignatureWithTrailingComment: per the
// CACHEDIR.TAG spec, the signature only needs to be a prefix of the
// first line — tools may append trailing content (e.g. comments).
// The walker must accept a tag like "Signature: ... # made by foo"
// and skip the directory.
func TestWalk_CachedirTagSignatureWithTrailingComment(t *testing.T) {
	root := t.TempDir()
	cache := filepath.Join(root, "cache")
	if err := os.Mkdir(cache, 0o755); err != nil {
		t.Fatal(err)
	}
	tag := "Signature: 8a477f597d28d172789f06886806bc55 # generated by foo"
	writeFile(t, filepath.Join(cache, "CACHEDIR.TAG"), tag)
	writeFile(t, filepath.Join(cache, "junk"), "x")
	writeFile(t, filepath.Join(root, "real.txt"), "r")

	fn, get := collectPaths()
	if err := Walk(context.Background(), root, Options{ExcludeCaches: true}, fn); err != nil {
		t.Fatal(err)
	}
	got := get()
	for _, p := range got {
		if strings.HasPrefix(p, "cache/") {
			t.Errorf("cache should be skipped, got %v in %v", p, got)
		}
	}
	if len(got) != 1 || got[0] != "real.txt" {
		t.Errorf("got %v, want [real.txt]", got)
	}
}

// TestWalk_DoesNotFollowSymlinks: a symlink (to a file or directory)
// is not a regular file under filepath.WalkDir's lstat semantics, so
// the walker should ignore it and emit no entry. Following symlinks
// is a v2 question; for now we want predictable, non-cyclic walks.
func TestWalk_DoesNotFollowSymlinks(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "real.txt"), "r")

	target := filepath.Join(root, "real.txt")
	link := filepath.Join(root, "link.txt")
	if err := os.Symlink(target, link); err != nil {
		t.Skipf("symlink unsupported on this filesystem: %v", err)
	}

	// Also add a symlinked directory to make sure we don't recurse
	// into the target.
	otherDir := t.TempDir()
	writeFile(t, filepath.Join(otherDir, "outside.txt"), "o")
	dirLink := filepath.Join(root, "dirlink")
	if err := os.Symlink(otherDir, dirLink); err != nil {
		t.Skipf("symlink unsupported on this filesystem: %v", err)
	}

	fn, get := collectPaths()
	if err := Walk(context.Background(), root, Options{}, fn); err != nil {
		t.Fatal(err)
	}
	got := get()
	slices.Sort(got)
	want := []string{"real.txt"}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v (symlinks must be skipped)", got, want)
	}
}

// TestWalk_IncludeNonRegular_EmitsSymlinksAndDirs: with the opt-in
// set, the walker emits directory entries (so empty dirs and dir
// modes survive a snapshot) and symlink entries carrying their target
// — without following either.
func TestWalk_IncludeNonRegular_EmitsSymlinksAndDirs(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "sub", "a.txt"), "a")
	if err := os.Mkdir(filepath.Join(root, "emptyd"), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("sub/a.txt", filepath.Join(root, "ln")); err != nil {
		t.Skipf("symlink unsupported on this filesystem: %v", err)
	}

	var mu sync.Mutex
	byPath := map[string]Entry{}
	err := Walk(context.Background(), root, Options{IncludeNonRegular: true}, func(e Entry) error {
		mu.Lock()
		byPath[e.RelPath] = e
		mu.Unlock()
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}

	if e, ok := byPath["emptyd"]; !ok || e.Kind != KindDir {
		t.Errorf("empty dir not emitted as KindDir: %+v", byPath["emptyd"])
	} else if e.Mode.Perm() != 0o700 {
		t.Errorf("dir mode: got %v, want 0700", e.Mode.Perm())
	}
	if e, ok := byPath["sub"]; !ok || e.Kind != KindDir {
		t.Errorf("non-empty dir not emitted as KindDir: %+v", byPath["sub"])
	}
	if e, ok := byPath["ln"]; !ok || e.Kind != KindSymlink {
		t.Errorf("symlink not emitted as KindSymlink: %+v", byPath["ln"])
	} else if e.LinkTarget != "sub/a.txt" {
		t.Errorf("symlink target: got %q, want %q", e.LinkTarget, "sub/a.txt")
	}
	if e, ok := byPath["sub/a.txt"]; !ok || e.Kind != KindFile {
		t.Errorf("regular file must stay KindFile: %+v", byPath["sub/a.txt"])
	}
	if _, ok := byPath["."]; ok {
		t.Error("the walk root itself must not be emitted")
	}
}

